"""Data dictionaries (EN, PT) and Kaggle metadata from schema/. Examples and null rates come from sample/.

    python scripts/docs.py
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
KAGGLE_TYPES = {"integer": "integer", "float": "number", "string": "string", "boolean": "boolean", "timestamp": "datetime"}


def example(series: pd.Series) -> str:
    values = series.dropna()
    values = values[values.astype(str) != ""]
    if values.empty:
        return ""
    text = str(values.iloc[len(values) // 2]).replace("\n", " ")
    text = text if len(text) <= 40 else text[:37] + "…"
    return "`" + text.replace("|", "\\|").replace("`", "'") + "`"


def dictionary(meta, columns, lang):
    pt = lang == "pt"
    lines = [f"# {'Dicionário de dados' if pt else 'Data dictionary'}: {meta['title_pt' if pt else 'title']}", "",
             ("Gerado por `scripts/docs.py` a partir de `schema/columns.json`. Nulos e exemplos vêm da amostra em `sample/`."
              if pt else "Generated by `scripts/docs.py` from `schema/columns.json`. Null rates and examples come from the sample in `sample/`."), ""]
    for table in meta["tables"]:
        frame = pd.read_csv(ROOT / "sample" / f"{table['name']}_sample.csv", dtype=str, keep_default_na=True)
        lines += [f"## `{table['name']}`", "", table["description_pt" if pt else "description"], "",
                  "| Coluna | Tipo | Nulos | Exemplo | Descrição |" if pt else "| Column | Type | Null | Example | Description |",
                  "|---|---|---|---|---|"]
        for col in (c for c in columns if c["table"] == table["name"]):
            s = frame[col["name"]] if col["name"] in frame else pd.Series(dtype=str)
            null = f"{s.isna().mean() * 100:.1f}%" if len(s) else ""
            null = null.replace(".", ",") if pt else null
            desc = col["description_pt" if pt else "description_en"].replace("|", "\\|")
            lines.append(f"| `{col['name']}` | {col['type']} | {null} | {example(s)} | {desc} |")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    meta = json.loads((ROOT / "schema" / "dataset.json").read_text(encoding="utf-8"))
    columns = json.loads((ROOT / "schema" / "columns.json").read_text(encoding="utf-8"))
    for table in meta["tables"]:
        header = pd.read_csv(ROOT / "sample" / f"{table['name']}_sample.csv", nrows=0).columns.tolist()
        names = [c["name"] for c in columns if c["table"] == table["name"]]
        if header != names:
            raise SystemExit(f"schema/columns.json is out of sync with sample/{table['name']}_sample.csv: {header}")
    (ROOT / "docs" / "data-dictionary.md").write_text(dictionary(meta, columns, "en"), encoding="utf-8")
    (ROOT / "docs" / "data-dictionary.pt-BR.md").write_text(dictionary(meta, columns, "pt"), encoding="utf-8")
    resources = []
    for table in meta["tables"]:
        fields = [{"name": c["name"], "description": c["description_en"], "type": KAGGLE_TYPES[c["type"]]}
                  for c in columns if c["table"] == table["name"]]
        resources.append({"path": f"{table['name']}.parquet", "description": table["description"], "schema": {"fields": fields}})
    kaggle = {"title": meta["kaggle_title"], "subtitle": meta["kaggle_subtitle"],
              "description": (ROOT / "docs" / "kaggle-description.md").read_text(encoding="utf-8"),
              "id": f"{meta['kaggle_user']}/{meta['slug']}", "licenses": [{"name": meta["kaggle_license"]}],
              "keywords": meta["keywords"], "isPrivate": False, "resources": resources}
    (ROOT / "kaggle").mkdir(exist_ok=True)
    (ROOT / "kaggle" / "dataset-metadata.json").write_text(json.dumps(kaggle, ensure_ascii=True, indent=2) + "\n", encoding="utf-8")
    print("docs/data-dictionary*.md and kaggle/dataset-metadata.json written")


if __name__ == "__main__":
    main()
